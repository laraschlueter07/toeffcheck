const brandKey = marke => marke.toLowerCase().replace(/[^a-z0-9]+/g, "-");

// Links zu MotoScout24 für ein Modell. Lieber allgemein und klar beschriftet als eine falsche Modellseite.
export function motoscoutLinks(model) {
  if (!model) return [{ label: "MotoScout24: allgemeine Suche", url: "https://www.motoscout24.ch/de/s", kind: "general" }];
  const brand = brandKey(model.marke);
  const pages = MODELLNAMEN[model.id]?.ms ?? [];
  if (!pages.length) return [{ label: `MotoScout24: alle ${model.marke}, Modell dort wählen`, url: `https://www.motoscout24.ch/de/s/mk-${brand}`, kind: "general" }];
  return pages.map(p => ({
    label: p.broad ? `MotoScout24: alle ${p.label}` : `MotoScout24: ${p.label}`,
    url: `https://www.motoscout24.ch/de/s/mo-${p.slug}/mk-${brand}`,
    kind: p.broad ? "broad" : "exact"
  }));
}
